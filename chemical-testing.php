                    body.style.display = 'none';
                    icon.classList.replace('fa-chevron-up', 'fa-chevron-down');
                    icon.style.backgroundColor = '#F1F5F9';
                    icon.style.color = '#64748B';
                    this.style.color = '#081D33';
                    parent.style.borderColor = '#E2E8F0';
                }
            });
        });
    });
