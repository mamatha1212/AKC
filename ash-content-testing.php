        </div>
        <h2 class="pr-section-title">🔬 Testing Methodology</h2>
        <p>ARC follows a rigorous, standardised process for ash content determination, ensuring consistent results with
            full traceability.</p>

        <div class="ash-steps-grid">
            <!-- Step 01 -->
            <div class="ash-step-card">
                <div class="ash-step-icon" style="font-size: 24px; margin-bottom: 10px;">📦</div>
                <span class="ash-step-num">Step 01</span>
                <h3 class="ash-step-title">Sample Preparation</h3>
                <p class="ash-step-desc">Representative sample is weighed to 4-5 decimal place accuracy using calibrated
                    analytical balance. Sample is pre-dried if required to remove moisture.</p>
            </div>
            <!-- Step 02 -->
            <div class="ash-step-card">
                <div class="ash-step-icon" style="font-size: 24px; margin-bottom: 10px;">🔥</div>
                <span class="ash-step-num">Step 02</span>
                <h3 class="ash-step-title">Controlled Combustion</h3>
                <p class="ash-step-desc">Sample is placed in a pre-ignited porcelain crucible and subjected to
                    controlled combustion in a muffle furnace at 550°C ± 25°C or 850°C per the applicable standard.</p>
            </div>
            <!-- Step 03 -->
            <div class="ash-step-card">
                <div class="ash-step-icon" style="font-size: 24px; margin-bottom: 10px;">📊</div>
                <span class="ash-step-num">Step 03</span>
                <h3 class="ash-step-title">Residue Measurement</h3>
                <p class="ash-step-desc">Cooled residue is weighed precisely. Ash content is calculated as percentage of
                    original sample mass. Full report with uncertainty is issued within 3-5 working days.</p>
            </div>
            <!-- Step 04 -->
            <div class="ash-step-card">
                <div class="ash-step-icon" style="font-size: 24px; margin-bottom: 10px;">📊</div>
                <span class="ash-step-num">Step 04</span>
                <h3 class="ash-step-title">Quality Assurance</h3>
                <p class="ash-step-desc">Final verification against client specifications or regulatory limits. Detailed
                    report is provided with ISO 17025 accreditation symbols where applicable.</p>
            </div>
        </div>
    </div>
</section>

