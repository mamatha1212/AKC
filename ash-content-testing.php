            <h2 class="pr-section-title">Plastic &amp; Resin Ash Content <span class="pr-blue">Testing Services</span>
            </h2>

            <p>Ash content testing is a fundamental analytical technique used to determine the quantity of inorganic
                residue (ash) that remains after a plastic or polymer material is subjected to complete controlled
                combustion. The inorganic residue typically consists of mineral fillers, glass fibres, pigments,
                stabilisers, flame retardants, or other inorganic additives incorporated during the manufacturing
                process.</p>

            <p>ARC's accredited laboratory conducts ash content determination in strict accordance with ISO 3451 and
                ASTM D5630, using muffle furnaces with precise temperature control and calibrated analytical balances to
                deliver accurate, reproducible results with full measurement uncertainty reporting.</p>

            <div class="pr-highlight-section" style="margin-top: 50px;">
                <h3 class="pr-sub-title">🔎 Why Ash Content Testing Matters</h3>
                <p>The ash content value provides manufacturers, quality managers, and regulatory compliance teams with
                    direct insight into the composition and quality of polymer materials. Key reasons this test is
                    specified include:</p>
                <ul class="pr-check-list">
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Verification that
                        filler or reinforcement loading (e.g. calcium carbonate, talc, glass fibre) meets specification
                    </li>
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Batch-to-batch
                        consistency assurance for compounded or filled polymer grades</li>
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Detection of
                        counterfeit or substituted materials with incorrect filler levels</li>
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Compliance with
                        material specifications in contractual, regulatory, or certification contexts</li>
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Identification of
                        recycled or contaminated resin through unexpected ash residue levels</li>
                    <li><span class="pr-blue" style="font-weight:bold; margin-right: 5px;">✓</span> Supporting food
                        contact, medical device, and toy safety compliance frameworks</li>
                </ul>
            </div>

