        function openModal(cardId) {
            const card = document.getElementById(cardId);
            const title = card.querySelector('.card-title').innerHTML;
            const desc = card.querySelector('.card-desc').innerHTML;

            // Clone the list element itself so we don't put li's directly into a div, or block elements directly into a ul
            const listElement = card.querySelector('.vm-list').cloneNode(true);
            listElement.style.display = 'block'; // Ensure it's visible in the modal

            document.getElementById('vmModalTitle').innerHTML = title;

            // Adjust title color based on card theme
            if (cardId === 'card-mission') {
                document.getElementById('vmModalTitle').style.color = '#e11d48'; // Red theme
            } else if (cardId === 'card-quality') {
                document.getElementById('vmModalTitle').style.color = '#059669'; // Green theme
            } else {
                document.getElementById('vmModalTitle').style.color = 'var(--primary-blue)'; // Blue theme
            }

            document.getElementById('vmModalDesc').innerHTML = desc;

            const modalContent = document.getElementById('vmModalContent');
            modalContent.innerHTML = ''; // Clear previous content
            modalContent.appendChild(listElement);

            const modal = document.getElementById('vmModal');
            modal.style.display = 'flex';
            document.body.style.overflow = 'hidden'; // Prevent background scrolling
        }

        function closeModal() {
            const modal = document.getElementById('vmModal');
            modal.style.display = 'none';
            document.body.style.overflow = 'auto'; // Re-enable background scrolling
        }

        // Close modal when clicking outside the white box
        window.onclick = function (event) {
            const modal = document.getElementById('vmModal');
            if (event.target == modal) {
                closeModal();
            }
        }
    </script>
